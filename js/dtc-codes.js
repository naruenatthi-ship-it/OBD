export function describeDtc(code) {
  const system = SYSTEMS[code[0]] ?? 'ไม่ทราบระบบ';
  // P1/P3 and B1/B2, C1/C2, U1/U2 are defined by each car maker.
  const manufacturer = code[0] === 'P' ? '13'.includes(code[1]) : '12'.includes(code[1]);
  let description = CODES[code];

  if (!description) {
    const group = code[0] === 'P' ? P_SUBSYSTEMS[code[2]] : null;
    description = manufacturer
      ? 'รหัสเฉพาะของผู้ผลิตรถ — ความหมายต่างกันในแต่ละยี่ห้อ ให้ค้นหาด้วยรหัสพร้อมรุ่นรถ'
      : 'ยังไม่มีคำอธิบายในฐานข้อมูล — ให้ค้นหาด้วยรหัสนี้';
    if (group) description += ` (กลุ่ม: ${group})`;
  }

  return { code, system, description, known: code in CODES, manufacturer, tip: TIPS[code] ?? null };
}
